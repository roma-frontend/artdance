import type { Page } from '@playwright/test';

/**
 * Отдельный адрес клиента на тест и на проект.
 *
 * Лимитеры продакшена считают обращения по адресу клиента, а все тесты набора
 * ходят с одного адреса 127.0.0.1. Общая корзина (например, `bookingHold` для
 * холдов и бронирований) заполняется соседними тестами, и тест, который дойдёт до
 * неё последним, получает 429 — хотя сам эндпоинт работает. Так падал клейм
 * листа ожидания в CI.
 *
 * Заголовок подменяет идентификатор клиента (`clientIdentifier` читает
 * `x-forwarded-for`), то есть тест изображает разных посетителей — а не отключает
 * защиту, ради которой она стоит. Передавайте в `seed` имя теста и имя проекта:
 * повтор упавшего теста в CI тогда идёт с того же адреса, а не с общего.
 */
export async function isolateRateLimit(page: Page, seed: string): Promise<void> {
  /* Адрес из блока для документации (RFC 5737): в сеть он не уйдёт. */
  const octet = ([...seed].reduce((sum, char) => sum + char.charCodeAt(0), 0) % 250) + 1;
  await page.setExtraHTTPHeaders({ 'x-forwarded-for': `198.51.100.${octet}` });
}
