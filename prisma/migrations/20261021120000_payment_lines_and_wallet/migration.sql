-- Покупки, которые не являются товарами магазина.
--
-- Пакеты занятий и пополнение кошелька продаются тем же путём, что и товары
-- (`Order` → `Payment` → провайдер), потому что отдельный кассовый контур
-- означал бы второй код прохождения оплаты, возврата и сверки. Различие —
-- только в типе линии: `settle.ts` по нему решает, что делать после оплаты.
--
-- Оба значения — добавления в enum, существующие строки не затрагиваются.

ALTER TYPE "LineItemType" ADD VALUE 'CLASS_PASS';
ALTER TYPE "LineItemType" ADD VALUE 'WALLET_TOPUP';

-- Сколько баланса списано с кошелька в этот заказ.
--
-- Нужно, чтобы повторный клик по «Оплатить» не списал баланс второй раз:
-- значение хранится на заказе, а не в памяти запроса, и идемпотентность
-- `WalletEntry.refId` не спасает — она вернула бы нулевое списание, и заказ
-- ушёл бы в провайдер на полную сумму.
ALTER TABLE "Order" ADD COLUMN "walletApplied" INTEGER NOT NULL DEFAULT 0;

-- Когда заказ доставлен до конца: пакет выдан, кошелёк пополнен, подписка
-- активирована, комиссия записана.
--
-- Отдельная колонка, а не «статус PAID означает и доставку»: подтверждение
-- оплаты приходит от провайдера, а доставка — наша работа, и между ними может
-- лежать сбой. Сравнение «null → дата» внутри одного `UPDATE` даёт
-- идемпотентность без блокировок: повторная доставка вебхука проигрывает гонку
-- и не выдаёт второй пакет.
ALTER TABLE "Order" ADD COLUMN "settledAt" TIMESTAMP(3);

-- Адрес доставки, введённый в оформлении, — снимком строкой.
--
-- `deliveryAddressId` ссылается на `Address`, а тот принадлежит пользователю:
-- у гостя адресной книги нет, а залогиненный может ввести новый адрес, не
-- сохраняя его в книгу. Курьеру нужен адрес именно этого заказа, даже если
-- запись в книге позже изменят. JSON, а не колонки: состав полей адреса
-- меняется, а снимок обязан остаться тем, что человек видел при оформлении.
ALTER TABLE "Order" ADD COLUMN "deliveryAddressSnapshot" JSONB;

-- Гостевой заказ: владелец без аккаунта.
--
-- Оформление гостю разрешено, и до этой колонки он мог создать заказ, но не
-- оплатить: `Order.userId` пуст, и сервер платежа не находит владельца.
-- Ключ — тот же `ARTDANCE_ANON_ID`, что и у корзины; он уже используется
-- для владения `Cart`, `SlotHold` и `Booking`, так что это не новый механизм,
-- а распространение существующего на заказ.
ALTER TABLE "Order" ADD COLUMN "anonymousId" TEXT;

-- Поиск своих гостевых заказов и сверка «кто владелец» идут по этому ключу.
CREATE INDEX "Order_anonymousId_placedAt_idx" ON "Order"("anonymousId", "placedAt");
