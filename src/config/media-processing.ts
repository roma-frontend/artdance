/**
 * Версия кадра под определённую ширину экрана.
 *
 * Одной версии не хватает, и это не оптимизация впрок. Кадр первого экрана
 * рисуется шириной 135% от окна (`--hero-wrap-width` — геометрия сдвига из
 * макета), то есть на мониторе 1440 это 1944 пикселя. Единственная версия в 1280
 * растягивалась там в полтора раза, и никакой битрейт этого не лечит: мыло
 * появляется при масштабировании, а не при сжатии. Обратная сторона: на телефоне
 * с окном 412 пикселей кадр рисуется шириной 556, и версия в 1920 — это
 * полтора мегабайта, скачанные, чтобы выбросить три четверти пикселей.
 *
 * Поэтому версий две, и выбирает их браузер по ширине окна.
 */
export interface VideoRendition {
  readonly width: number;
  readonly height: number;
  /**
   * Минимальная ширина кадра в ФИЗИЧЕСКИХ пикселях, которую требует экран, от
   * которой применяется эта версия (см. `requiredFrameWidth` в
   * `src/lib/media/video-source.ts`). Выбирается последняя подходящая, поэтому у
   * самой мелкой здесь `0`.
   */
  readonly minViewportWidth: number;
  /**
   * kbit/s по форматам. Числа заданы на версию, а не выведены из площади кадра:
   * потребность в битах растёт медленнее числа пикселей, и линейный пересчёт
   * давал бы 1080p вдвое дороже, чем нужно.
   */
  readonly bitrateKbps: Readonly<Record<'av1' | 'vp9' | 'h264', number>>;
}

/**
 * Параметры кодирования одной фоновой петли.
 *
 * Выделены в тип, потому что петля на странице не одна: первый экран и
 * editorial-секция. Общий тип означает, что скрипт кодирования, проверка
 * бюджета и выбор источника в браузере работают с любой петлёй, а не только с
 * hero, — и добавление третьей не потребует ни одной новой ветки в коде.
 */
export interface VideoLoopPolicy {
  /** Имя файлов петли в `public/media/video`: `<baseName>-<ширина>-<отпечаток>`. */
  readonly baseName: string;
  /** Бюджет на ОДИН файл — самой тяжёлой версии в самом дорогом формате. */
  readonly maxBytes: number;
  readonly maxDurationSeconds: number;
  /** Версии кадра по возрастанию ширины. */
  readonly renditions: readonly VideoRendition[];
  readonly targetFps: number;
  readonly formats: readonly ('av1' | 'vp9' | 'h264')[];
  readonly stripAudio: boolean;
  /**
   * Длительность перекрёстного растворения хвоста в начало, секунды. `0` —
   * склейки нет.
   *
   * Нужно тогда, когда исходник не является петлёй: у присланного клипа
   * последний кадр не совпадает с первым, и на шве каждые несколько секунд
   * происходит скачок — в полноэкранной секции он заметнее всего остального.
   * Хвост длиной `seamCrossfadeSeconds` растворяется в начало, и петля
   * замыкается сама на себя. Цена — та же длительность минус время склейки.
   */
  readonly seamCrossfadeSeconds: number;
  /**
   * Прямоугольник, который заклеивается интерполяцией (`delogo`): `null` —
   * заклеивать нечего.
   *
   * Генераторы видео ставят свой знак в угол кадра. Обрезать его нельзя без
   * потери композиции (знак отстоит от края на десятую часть кадра), а
   * затемняющий слой его не скрывает: знак светлее фона. `delogo` достраивает
   * область по краям прямоугольника — на почти чёрном фоне шва не видно.
   */
  readonly removeWatermark: { x: number; y: number; width: number; height: number } | null;
  /**
   * Клип не проигрывается сам, а отматывается прокруткой: позиция во времени
   * равна прогрессу скролла. `null` — обычная петля, которая играет.
   *
   * Отдельный профиль сжатия нужен из-за того, как работает отматывание. Браузер
   * умеет показать только ключевой кадр или кадр, восстановленный от ближайшего
   * предыдущего ключевого. При обычном для веба интервале (кадр раз в 2–10
   * секунд) на каждый шаг прокрутки декодеру приходится разбирать десятки
   * промежуточных кадров, и картинка идёт ступенями. Частые ключевые кадры
   * снимают это ценой веса — поэтому интервал объявлен политикой, а не выбран
   * энкодером по умолчанию.
   *
   * Замерено на клипе первого экрана: интервал 8 кадров при 24 fps добавляет к
   * файлу около 15% — тёмный дымный кадр сжимается хорошо, и разница между
   * ключевым и обычным кадром на нём мала.
   */
  readonly scrub: {
    /** Расстояние между ключевыми кадрами, в кадрах. */
    readonly keyframeIntervalFrames: number;
  } | null;
  /**
   * Кодировать от конца к началу.
   *
   * Нужно обратному проходу раскрытия: назад видео воспроизвести нельзя, а
   * перемотка идёт неровно. Перевёрнутый клип играется вперёд, то есть плавен по той
   * же причине, по которой плавен прямой.
   */
  readonly reversed: boolean;
  /**
   * Снимать ли постер с первого кадра.
   *
   * У перевёрнутого клипа первый кадр — открытая сцена, и постером она быть не
   * может: постер показывается до начала раскрытия. Второй файл в папке сид-медиа
   * потребовал бы ещё и альтернативного текста на трёх языках — за изображение,
   * которое никто не увидит.
   */
  readonly extractsPoster: boolean;
}

