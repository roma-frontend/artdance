/**
 * RANKING — веса выдачи каталога.
 *
 * Порядок в листинге определяет, кто получит бронь, то есть это распределение
 * денег между исполнителями. Поэтому веса лежат здесь, а не в `ORDER BY` и не в
 * коде компонента: «поднимите проверенных» и «перестаньте наказывать за одну
 * отмену» должны быть правкой одной строки, а решение — обсуждаемым.
 *
 * Сумма весов равна 100, каждый сигнал нормализован в [0, 1]. Отсюда шкала:
 * базовый счёт всегда 0…100, а бонусы (новичок, платное продвижение) добавляются
 * сверху и потому видны в разборе счёта отдельной строкой.
 *
 * @confirm с заказчиком: приоритеты выдачи — коммерческое решение, а не техническое.
 */

export const ranking = {
  /**
   * Веса сигналов. Сумма — 100; проверяется тестом, потому что «поправил один
   * вес» без пересчёта остальных незаметно меняет шкалу всего каталога.
   */
  weights: {
    /** Средняя оценка со сглаживанием по числу отзывов. */
    rating: 28,
    /** Сколько отзывов вообще есть: 4.9 по трём отзывам слабее 4.7 по ста. */
    reviewVolume: 12,
    /** Заполняемость занятий: пустые группы никому не помогают. */
    fillRate: 12,
    /** Скорость ответа на заявку. */
    responsiveness: 8,
    /** Надёжность: отмены и неявки со стороны исполнителя. */
    reliability: 20,
    /** Опыт на платформе: число проведённых занятий. */
    experience: 10,
    /** Пройденная проверка документов. */
    verification: 10,
  },

  /**
   * Сколько отзывов считать достаточным, чтобы оценка весила полностью.
   *
   * Используется дважды: как знаменатель сигнала «объём отзывов» и как сила
   * байесовского сглаживания. Одно число, потому что смысл один — «с этого места
   * оценке можно верить».
   */
  reviewConfidenceCount: 25,

  /**
   * К какой оценке тянется средняя при малом числе отзывов.
   *
   * Без сглаживания первый же отзыв на пять звёзд выносит нового исполнителя выше
   * всех, а первый на три — закапывает. Приор — это «пока не знаем, считаем
   * средним по платформе».
   */
  ratingPrior: 4.2,

  /** Время ответа, после которого сигнал обнуляется. Сутки — это уже «не ответил». */
  responseTimeCeilingMinutes: 24 * 60,

  /** Сколько проведённых занятий считать полным опытом. */
  experienceSaturationBookings: 100,

  /**
   * Неявка исполнителя весит больше отмены: отмена оставляет клиенту время найти
   * замену, неявка — нет.
   */
  noShowSeverity: 2,

  /**
   * Поддержка новичка.
   *
   * Без неё исполнитель без отзывов не получит первую бронь, а без первой брони
   * не получит отзывов. Бонус убывает линейно и исчезает вместе с окном — это не
   * преимущество, а компенсация отсутствующих сигналов.
   */
  newcomer: {
    windowDays: 30,
    maxBonus: 15,
  },

  /**
   * Платное продвижение.
   *
   * Карточка с активным бустом ОБЯЗАНА быть помечена в интерфейсе: скрытая
   * реклама в выдаче — это и обман пользователя, и правовой риск. Пометка живёт в
   * компоненте карточки, но решение о ней принято здесь, вместе с бонусом.
   */
  boostedBonus: 25,
} as const;

export type RankingWeights = typeof ranking.weights;
export type RankingSignalName = keyof RankingWeights;
