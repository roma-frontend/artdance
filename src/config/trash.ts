/**
 * КОРЗИНА — удаление в два шага.
 *
 * Удаление из админки не стирает запись, а ставит `deletedAt`. Причина простая:
 * «удалите это занятие» и «удалите не то занятие» выглядят на экране одинаково,
 * а последствия разные — у второго нет отката, если запись стёрта.
 *
 * ЧТО ЗДЕСЬ ОБЪЯВЛЕНО И ПОЧЕМУ ИМЕННО ЗДЕСЬ
 *
 * Список моделей — единственный источник правды на весь проект. По нему:
 *  • клиент Prisma прячет удалённое из ЛЮБОГО чтения (`src/lib/db.ts`);
 *  • тест сверяет, что у каждой модели действительно есть колонка `deletedAt`
 *    и что её уникальные ограничения частичные (`trash.test.ts`);
 *  • раздел «Корзина» знает, что показывать;
 *  • cron знает, что чистить.
 *
 * Второй список в другом месте разошёлся бы с этим — и разошёлся бы молча:
 * забытая модель означает, что удалённая запись остаётся в публичном каталоге.
 *
 * ЧТО В КОРЗИНУ НЕ ПОПАДАЕТ
 *
 * Заказы, брони, платежи, возвраты, выплаты, комиссии, подарочные карты и журнал
 * аудита. У них нет и не должно быть удаления вообще: история денег и решений не
 * удаляется — это правило из `10-hard-rules`, а не осторожность. Отменённый
 * заказ остаётся заказом со статусом `CANCELLED`.
 */

/**
 * Модели с мягким удалением. Имена — как в `prisma/schema.prisma`: по ним
 * выводится и делегат клиента, и проверка схемы.
 */
export const trashedModels = [
  'DanceClass',
  'ClassSession',
  'InstructorProfile',
  'Venue',
  'Room',
  'Product',
  'ProductCategory',
  'ProductVariant',
  'Event',
  'Course',
  'CourseLesson',
  'PromoCode',
  'MediaAsset',
] as const;

export type TrashedModel = (typeof trashedModels)[number];

const trashedModelSet: ReadonlySet<string> = new Set(trashedModels);

export function isTrashedModel(model: string): boolean {
  return trashedModelSet.has(model);
}

/**
 * Имя делегата Prisma по имени модели: `DanceClass` → `danceClass`.
 *
 * Объявлено здесь, а не в трёх местах, где нужно: расширение клиента, реестр
 * админки и чистка по расписанию обращаются к делегатам по строке, и три копии
 * одного преобразования — это три места, где опечатка даёт «нет делегата».
 */
export function modelDelegateKey(model: string): string {
  return model.charAt(0).toLowerCase() + model.slice(1);
}

/**
 * Операции чтения, из которых удалённое вырезается автоматически.
 *
 * `findUnique` в списке намеренно: Prisma принимает в его `where` не только
 * уникальные поля, поэтому «найти по id» тоже обязано не находить удалённое —
 * иначе гвард владения пропустил бы запись, которой для приложения уже нет.
 *
 * Вложенные чтения (`select: { media: … }`) расширениями клиента НЕ
 * перехватываются — это ограничение Prisma. Для них фильтр объявлен в общих
 * константах связей (`src/server/queries/relations.ts`), и их наличие проверяет
 * тест: это единственное место, где о корзине нужно помнить руками.
 */
export const trashFilteredOperations = [
  'findFirst',
  'findFirstOrThrow',
  'findMany',
  'findUnique',
  'findUniqueOrThrow',
  'count',
  'aggregate',
  'groupBy',
] as const;

const trashFilteredOperationSet: ReadonlySet<string> = new Set(trashFilteredOperations);

export function isTrashFilteredOperation(operation: string): boolean {
  return trashFilteredOperationSet.has(operation);
}

export const trash = {
  /**
   * Сколько запись лежит в корзине до окончательного удаления.
   *
   * Без срока корзина растёт вечно, и «удалено» перестаёт что-либо значить: в
   * ней окажется весь когда-либо созданный контент. Месяц — это интервал, за
   * который ошибку замечают: он покрывает отпуск и закрытие месяца.
   */
  retentionDays: 30,

  /**
   * Сколько записей чистка удаляет за один запуск.
   *
   * Ограничение против длинной транзакции на первом же запуске после долгого
   * простоя: удалить сразу десять тысяч записей с каскадами значит держать
   * блокировки минутами. Остаток уйдёт на следующем запуске.
   */
  purgeBatchSize: 200,

  /**
   * Сколько записей показывает страница корзины.
   *
   * Корзина — не каталог: в ней ищут недавно удалённое, а не листают историю.
   */
  pageSize: 25,
} as const;
