/**
 * Обратная связь на ожидание: скелеты и индикатор перехода.
 *
 * Числа здесь, а не в компонентах, ровно по той же причине, что и остальные
 * параметры движения: «сделайте мерцание поспокойнее» должно быть правкой одной
 * строки. Но у этих чисел есть ещё одно свойство — они определяют, покажется
 * индикатор вообще или нет, и подобранное «на глаз» значение даёт вспышку на
 * каждом переходе.
 */
export const loadingMotion = {
  /**
   * Задержка перед показом индикатора нажатой ссылки.
   *
   * Переходы в основном мгновенные: страницы префетчатся, и ответ приходит
   * быстрее, чем человек замечает. Индикатор без задержки успевает мигнуть на
   * каждом щелчке — это шум, который читается как «что-то сломалось». Порог
   * примерно равен границе, за которой задержку начинают ощущать.
   */
  pendingDelayMs: 220,
  /** Длительность цикла мерцания скелета. */
  shimmerMs: 1_400,
  /**
   * Сколько строк рисует скелет списка по умолчанию.
   *
   * Скелет обязан повторять геометрию финального блока: скелет «на глаз» даёт
   * скачок вёрстки при подмене, и это ухудшает CLS сильнее, чем его отсутствие.
   */
  skeletonRows: 6,
} as const;

