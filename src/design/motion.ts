/**
 * Раскрытие первого экрана прокруткой — «занавес».
 *
 * Заменило прежний параллакс ухода (05.09.2026). Прежняя механика двигала слои
 * от `window.scrollY` в пикселях: фон 0.3 вниз, содержимое −0.6 вверх, всё
 * заканчивалось на 0.85 высоты экрана. Она описывала экран, который УЕЗЖАЕТ, и к
 * новому первому экрану неприменима — здесь экран стоит на месте, приколотый
 * `position: sticky`, а прокрутка отматывает клип с раскрытием занавеса.
 *
 * Доля раскрытия (0…1) считается по ВСЕМУ пути первого экрана: от касания верхней
 * кромки окна до момента, когда следующая секция встаёт под шапку. Единица — это
 * одновременно последний кадр клипа и приход второй секции. Так задано намеренно:
 * заказчик просил, чтобы конец видео и подход ко второй секции совпадали, а не шли
 * друг за другом. Приколотая часть занимает первую половину пути
 * (`pinEndsAtProgress`), вторую экран уходит вверх — и последние кадры клипа идут
 * уже на уходе. Кадры там почти не меняются: камера к сцене уже подъехала.
 *
 * Промежуточных положений не существует: жест запускает доигрывание, и раскрытие
 * приходит либо в ноль, либо в единицу.
 *
 * Текст первого экрана НЕ двигается и НЕ гаснет (решение заказчика от 05.09.2026):
 * он виден до конца. Отсюда и направление вуали — она густеет, а не растворяется.
 */
/**
 * Доля общего пути, на которой заканчивается приколотая часть.
 *
 * Выведена, а не выбрана: полоса разгона относится к полному пути как
 * `runway / (viewport + runway)`. Всё, что должно случиться, пока экран стоит на
 * месте, привязано к этому числу — тогда изменение полосы разгона не рассыпает
 * остальные пороги.
 */
const revealRunwayViewports = 1;
const pinEndsAtProgress = revealRunwayViewports / (1 + revealRunwayViewports);

export const heroParallax = {
  /**
   * Полоса прокрутки, отведённая раскрытию, в высотах области просмотра.
   *
   * Единица означает: первый экран занимает две высоты окна — одну видно, вторая
   * тратится на раскрытие, пока кадр приколот.
   *
   * При `prefers-reduced-motion` полоса не существует вовсе: экран остаётся
   * высотой в одно окно, и это правило CSS, а не ветка в коде.
   */
  revealRunwayViewports,
  pinEndsAtProgress,
  /**
   * Скорость воспроизведения при доигрывании.
   *
   * Раскрытие доигрывается НАСТОЯЩИМ воспроизведением, а не перемоткой, и это не
   * оптимизация, а единственный способ получить плавность. Перемотка (`currentTime`)
   * заставляет декодер собрать кадр по запросу; таких запросов при прокрутке
   * десятки в секунду, они выполняются неравномерно, и движение читается как
   * перелистывание. Воспроизведение — то, для чего декодер и построен: кадры идут
   * ровным потоком, аппаратно.
   *
   * Клип десять секунд; на 2.5 полный проход занимает четыре. Это осознанно долго:
   * заказчик просил, чтобы видео проигрывалось целиком и плавно. Быстрее — и
   * движение снова начинает читаться как перелистывание, только уже по вине
   * скорости, а не декодера.
   *
   * Число может быть срезано браузером (Safari ограничивает высокие скорости).
   * Это не ломает синхронность: прокрутка следует за фактическим временем клипа, а
   * не за расчётным, поэтому при любой фактической скорости кадр и положение
   * страницы совпадают.
   */
  revealPlaybackRate: 2.5,
  /**
   * Предохранитель: сколько ждать доигрывания, прежде чем отпустить прокрутку, мс.
   *
   * Во время доигрывания прокрутка удерживается — иначе посетитель останавливает
   * раскрытие на середине, а промежуточных положений в замысле нет. Но удержание
   * без предела означало бы заблокированную страницу, если клип встал на буферизации
   * и воспроизведение не двигается. Предел считается от полного прохода с запасом.
   */
  revealLockTimeoutMs: 9_000,
  /**
   * Шаг обратного прохода, в кадрах клипа.
   *
   * Назад воспроизвести нельзя: отрицательной скорости у видео не бывает, а
   * перевёрнутая копия клипа удвоила бы вес первого экрана. Поэтому обратный проход
   * идёт перемоткой — но НЕ по часам.
   *
   * Первая версия вела перемотку по времени, как анимацию, и посетитель увидел
   * ровно то, что должен был: «местами ускоряется». Причина в том, что перемотка
   * занимает неизвестное время — от единиц до десятков миллисекунд в зависимости от
   * того, где в файле ближайший ключевой кадр и чем занят декодер. Часы этого не
   * знают, и там, где декодер успевал, кадры шли пачками.
   *
   * Поэтому шаг задан в кадрах, а следующий запрашивается только после того, как
   * предыдущий доехал (`seeked`). Темп получается тот, который декодер способен
   * держать, зато РОВНЫЙ — а ровность здесь и есть плавность.
   */
  revealRewindStepFrames: 1,
  /**
   * Плотность затемнения под текстом в НАЧАЛЕ раскрытия.
   *
   * Вуаль не растворяется по ходу раскрытия, а густеет — и это следствие решения
   * заказчика от 05.09.2026: текст первого экрана остаётся на виду до конца.
   *
   * Прежде было наоборот: текст гас к 0.13, а вместе с ним уходила и вуаль.
   * Логика была в том, что защищать больше нечего. Если текст остаётся, логика
   * переворачивается: в начале за ним почти абсолютно чёрный бархат и вуаль почти
   * не нужна, а к концу приходит открытая сцена — ivory-заголовок на ней теряет
   * контраст, и вуаль обязана быть плотнее всего именно там.
   *
   * Половина в начале — компромисс: меньше не держит контраст на средних долях
   * раскрытия, больше съедает фактуру бархата, по которой читается, что это ткань.
   */
  overlayOpacityAtStart: 0.5,
  /**
   * Доля пути, на которой вуаль набирает полную плотность.
   *
   * Привязана к приколотой части: к моменту, когда экран начинает уходить, свет уже
   * пришёл, и защищать текст нужно на полную. Дальше густеть незачем.
   */
  overlayFullAtProgress: pinEndsAtProgress * 0.7,
  /**
   * Укрупнение кадра к концу раскрытия.
   *
   * 1.3 — не «на глаз», а предел без потери резкости: широкая версия кадра 1920,
   * типичное окно 1440, и 1920 / 1.3 = 1477 исходных точек всё ещё больше 1440
   * экранных. Выше этого числа начинается растягивание пикселей, то есть ровно то
   * мыло, из-за которого раскрытие нельзя было сделать простым зумом в щель.
   */
  tailZoom: 1.3,
  /** Доля пути, с которой начинается укрупнение. */
  tailZoomFromProgress: pinEndsAtProgress * 0.55,
  /**
   * Доля пути, на которой укрупнение закончено.
   *
   * Ровно конец приколотой части: увеличивать кадр, который уже уезжает вверх,
   * значит добавлять второе движение к уходу — глаз читает это как рывок.
   */
  tailZoomFullAtProgress: pinEndsAtProgress,
  /**
   * Порог перемотки, в кадрах. Запрос на меньшее смещение отбрасывается:
   * перемотка внутри одного кадра не меняет картинку, но заставляет декодер
   * работать на каждое событие прокрутки.
   */
  seekThresholdFrames: 0.5,
} as const;

