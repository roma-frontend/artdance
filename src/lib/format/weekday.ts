/**
 * Название дня недели на языке страницы.
 *
 * Задача выглядит тривиальной, но у неё есть ровно одна ловушка: `Intl` умеет
 * форматировать только дату, а «суббота» в расписании — это не дата, а номер
 * дня. Поэтому нужен якорь: любая заведомо известная неделя, от которой
 * отсчитывается нужный день.
 *
 * Альтернатива — держать названия дней в каталоге переводов — хуже: это данные
 * платформы `Intl`, они уже есть в браузере и на сервере, и дублировать их
 * вручную для трёх языков означает однажды получить «Понеділок» в армянской
 * локали. Плюс `Intl` знает падежи и сокращения, которых в наивном списке нет.
 *
 * Якорь: 4 января 1970 года — воскресенье. Индексация совпадает с
 * `Date.getDay()`: 0 — воскресенье, 6 — суббота. UTC, чтобы часовой пояс
 * машины не сдвинул день.
 */

/** Воскресенье. Совпадает с нулём в `Date.getDay()`. */
const ANCHOR_SUNDAY_UTC = Date.UTC(1970, 0, 4);
const MS_PER_DAY = 24 * 60 * 60 * 1000;

/**
 * Дата, у которой день недели равен переданному номеру. Нужна только для
 * форматирования: сама дата смысла не несёт и в интерфейс не попадает.
 */
export function dateForWeekday(weekday: number): Date {
  const normalized = ((weekday % 7) + 7) % 7;
  return new Date(ANCHOR_SUNDAY_UTC + normalized * MS_PER_DAY);
}
