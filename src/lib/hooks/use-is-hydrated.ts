/**
 * Прошла ли гидратация.
 *
 * Нужен там, где первый клиентский кадр обязан совпасть с серверным, а
 * настоящее значение известно только браузеру: выбранная тема, точность
 * указателя, содержимое `localStorage`. Компонент рисует нейтральное состояние
 * до гидратации и настоящее — после.
 *
 * Через `useSyncExternalStore` с подпиской-заглушкой, а не через `useEffect` +
 * `setState`: правило `react-hooks/set-state-in-effect` запрещает второе, и
 * запрещает справедливо — здесь нет внешнего события, есть только факт «мы уже
 * в браузере», и React умеет сообщить его сам, разными снимками для сервера и
 * клиента.
 */

'use client';

import { useSyncExternalStore } from 'react';

/** Значение никогда не меняется, поэтому подписка ничего не слушает. */
const subscribe = () => () => {};

export function useIsHydrated(): boolean {
  return useSyncExternalStore(
    subscribe,
    () => true,
    () => false,
  );
}
